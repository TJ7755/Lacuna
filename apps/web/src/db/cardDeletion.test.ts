import 'fake-indexeddb/auto';
import { beforeEach, describe, expect, it } from 'vitest';
import { db } from './schema';
import { reviewHistoryEntryIdForEvent } from './reviewHistory';
import { createCard, createCourse, deleteCards, restoreCards, snapshotCards } from './repository';

describe('cardDeletion', () => {
  beforeEach(async () => {
    await Promise.all([db.schedulingUnits.clear(), db.cards.clear(), db.reviewHistory.clear()]);
  });

  it('deletes ordinary cards', async () => {
    const deck = await createCourse('Bulk');
    const b = await createCard(deck.id, 'front_back', 'b', '2');

    await deleteCards([b.id]);
    expect(await db.cards.get(b.id)).toBeUndefined();
  });

  it('replaces canonical history with the captured card snapshot', async () => {
    const deck = await createCourse('Snapshot history');
    const card = await createCard(deck.id, 'front_back', 'q', 'a');
    const snapshot = await snapshotCards([card.id]);
    await db.reviewHistory.add({
      id: reviewHistoryEntryIdForEvent('event-after-card-snapshot'),
      eventId: 'event-after-card-snapshot',
      cardId: card.id,
      deckId: card.deckId,
      schedulingUnitId: card.schedulingUnitId,
      timestamp: 100,
      grade: 3,
      responseTimeSec: 2,
      distracted: false,
      stabilityBefore: null,
      stabilityAfter: 2,
      difficultyBefore: null,
      difficultyAfter: 5,
      retrievabilityAtReview: null,
    });

    await restoreCards(snapshot);

    expect(await db.reviewHistory.where('cardId').equals(card.id).count()).toBe(0);
  });

  it('refuses to delete sequence-generated cards', async () => {
    const deck = await createCourse('Bulk');
    const a = await createCard(deck.id, 'front_back', 'a', '1');
    await db.cards.update(a.id, { sequenceItemId: 'seq-item-1' });

    await expect(deleteCards([a.id])).rejects.toThrow(
      'One or more cards were generated by a sequence or occlusion and can only be deleted or moved via that sequence or occlusion.',
    );
    expect(await db.cards.get(a.id)).toBeDefined();
    expect((await db.cards.get(a.id))!.deckId).toBe(deck.id);
  });
});
